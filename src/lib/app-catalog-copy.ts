function appCategoryKey(category: string): LocaleKey | undefined {
  const normalized = category.trim().toLowerCase().replace(/[_-]+/g, " ").replace(/&/g, " and ").replace(/\s+/g, " ");
  return Object.hasOwn(APP_CATEGORY_LABELS, normalized) ? APP_CATEGORY_LABELS[normalized] : undefined;
}

export function appCategoryLabel(category: string): string {
  const key = appCategoryKey(category);
  return key ? t(key) : category;
}

export function appBlurb(card: AppCopyCard): string {
  const normalized = card.slug.toLowerCase().replace(/[_-]/g, "");
  const key = Object.hasOwn(APP_BLURBS, normalized) ? APP_BLURBS[normalized] : undefined;
  if (key) return t(key);
  if (activeLocale() !== "zh" || /\p{Script=Han}/u.test(card.blurb)) return card.blurb;
  const categories = [...new Set((card.categories ?? []).flatMap((category) => {
    const categoryKey = appCategoryKey(category);
    return categoryKey ? [t(categoryKey)] : [];
  }))];
  return categories.length
    ? t("apps.blurb.categoryFallback", { categories: categories.join("、") })
    : t("apps.blurb.genericFallback");
}

export function appDescriptionTitle(card: AppCopyCard, description = appBlurb(card)): string {
  return activeLocale() === "zh" && card.blurb && card.blurb !== description && description === appBlurb(card)
    ? description + "\n\n" + t("apps.blurb.original") + "\n" + card.blurb
    : description;
}
